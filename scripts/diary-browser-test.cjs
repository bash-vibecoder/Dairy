      const NativeDate = Date;
      const fixed = NativeDate.parse('2026-11-18T15:00:00Z');
      window.__now = Number(sessionStorage.getItem('diary-test-now')) || fixed;
      window.Date = class extends NativeDate { constructor(...args) { super(...(args.length ? args : [window.__now])); } static now() { return window.__now; } };
      window.__clockTicks = [];
      const nativeSetInterval = window.setInterval.bind(window);
